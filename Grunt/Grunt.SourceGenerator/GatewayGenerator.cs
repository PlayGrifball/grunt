using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Grunt.SourceGenerator;

/// <summary>
/// Generates the Halo gateway from [GatewayExposed] methods of a client class (normally HaloInfiniteClient, read from the
/// referenced Surprenant.Grunt assembly):
/// <list type="bullet">
/// <item>In a project with <c>[assembly: GenerateGatewayController(typeof(HaloInfiniteClient))]</c>: an ASP.NET Core
/// <c>partial class HaloInfiniteController : ControllerBase</c>, one action per exposed method, calling the injected
/// IHaloInfiniteClient (which the host binds to HaloInfiniteClientFactory, so auth retry and backoff stay in one place).</item>
/// <item>In a project with <c>[assembly: GenerateGatewayClient(typeof(HaloInfiniteClient))]</c>: <c>partial class
/// HaloGatewayClient : IHaloInfiniteClient</c> calling those routes; other interface methods throw NotSupportedException.</item>
/// </list>
/// The marker attribute selects the output, so the core library never references ASP.NET Core for this.
/// </summary>
[Generator]
public sealed class GatewayGenerator : IIncrementalGenerator
{
    public const string ControllerClassName = "HaloInfiniteController";
    public const string ClientClassName = "HaloGatewayClient";

    private const string Results = "global::Surprenant.Grunt.Gateway.HaloGatewayResults";
    private const string CacheAttribute = "global::Surprenant.Grunt.Gateway.HaloGatewayCacheAttribute";
    private const string CachePolicyEnum = "global::Surprenant.Grunt.Attributes.GatewayCachePolicy";
    private const string Transport = "global::Surprenant.Grunt.Gateway.Client.HaloGatewayTransport";
    private const string ClientOptions = "global::Surprenant.Grunt.Gateway.Client.HaloGatewayClientOptions";
    private const string UriHelper = "global::Surprenant.Grunt.Gateway.Client.HaloGatewayUri";
    private const string Mvc = "global::Microsoft.AspNetCore.Mvc";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(context.CompilationProvider, static (spc, compilation) => Execute(spc, compilation));
    }

    private static void Execute(SourceProductionContext context, Compilation compilation)
    {
        var controllerTarget = GatewayModelBuilder.ReadTarget(compilation, GatewayModelBuilder.ControllerAttributeName);
        if (controllerTarget is not null && Prepare(context, controllerTarget))
        {
            context.AddSource($"{ControllerClassName}.generated.cs", SourceText.From(EmitController(controllerTarget), Encoding.UTF8));
        }

        var clientTarget = GatewayModelBuilder.ReadTarget(compilation, GatewayModelBuilder.ClientAttributeName);
        if (clientTarget is not null && Prepare(context, clientTarget))
        {
            context.AddSource($"{ClientClassName}.generated.cs", SourceText.From(EmitClient(clientTarget), Encoding.UTF8));
        }
    }

    private static bool Prepare(SourceProductionContext context, GatewayTarget target)
    {
        if (target.InterfaceType is null)
        {
            context.ReportDiagnostic(Diagnostic.Create(GatewayDiagnostics.MissingInterface, Location.None,
                "I" + target.ClientType.Name, target.ClientType.ToDisplayString()));
            return false;
        }
        GatewayModelBuilder.Populate(target, context.ReportDiagnostic);
        return true;
    }

    internal static string EmitController(GatewayTarget target)
    {
        var iface = GatewayModelBuilder.TypeName(target.InterfaceType!);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// Generated by Grunt.SourceGenerator.GatewayGenerator from [GatewayExposed] methods of " + target.ClientType.ToDisplayString() + ".");
        sb.AppendLine("#nullable disable");
        sb.AppendLine();
        sb.AppendLine($"namespace {target.Namespace};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Halo gateway: one action per [GatewayExposed] method of {target.ClientType.Name}. Every action calls the injected");
        sb.AppendLine($"/// {target.InterfaceType!.Name} (HaloInfiniteClientFactory in the host), which owns auth retry and backoff; actions do not retry.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"[{Mvc}.ApiController]");
        sb.AppendLine($"[{Mvc}.Route({GatewayModelBuilder.Literal(target.RoutePrefix)})]");
        sb.AppendLine($"public partial class {ControllerClassName} : {Mvc}.ControllerBase");
        sb.AppendLine("{");
        sb.AppendLine($"    private readonly {iface} _client;");
        sb.AppendLine("    private readonly global::Microsoft.Extensions.Logging.ILogger _logger;");
        sb.AppendLine();
        sb.AppendLine($"    /// <summary>Creates the controller over <paramref name=\"client\"/>.</summary>");
        sb.AppendLine($"    public {ControllerClassName}({iface} client, global::Microsoft.Extensions.Logging.ILogger<{ControllerClassName}> logger)");
        sb.AppendLine("    {");
        sb.AppendLine("        _client = client;");
        sb.AppendLine("        _logger = logger;");
        sb.AppendLine("    }");

        foreach (var m in target.Methods)
        {
            var containerType = GatewayModelBuilder.TypeName(((INamedTypeSymbol)m.Method.ReturnType).TypeArguments[0]);
            var resultType = GatewayModelBuilder.TypeName(m.ResultType);
            var verb = m.HttpMethod switch
            {
                "POST" => "HttpPost",
                "PUT" => "HttpPut",
                "PATCH" => "HttpPatch",
                "DELETE" => "HttpDelete",
                _ => "HttpGet",
            };

            sb.AppendLine();
            sb.AppendLine($"    /// <summary>{m.HttpMethod} {GatewayModelBuilder.Xml(target.RoutePrefix + "/" + m.Route)} → {GatewayModelBuilder.Xml(GatewayModelBuilder.Display(m.Method))}.</summary>");
            sb.AppendLine($"    [{Mvc}.{verb}({GatewayModelBuilder.Literal(m.Route)})]");
            if (m.CachePolicy != 0)
            {
                sb.AppendLine($"    [{CacheAttribute}(({CachePolicyEnum}){m.CachePolicy}, {m.CacheSeconds})]");
            }
            if (m.IsBinary)
            {
                sb.AppendLine($"    [{Mvc}.ProducesResponseType(typeof(byte[]), 200, \"application/octet-stream\")]");
            }
            else
            {
                sb.AppendLine($"    [{Mvc}.ProducesResponseType(typeof({containerType}), 200)]");
            }

            var parameters = new List<string>();
            var args = new List<string>();
            foreach (var p in m.Parameters)
            {
                var name = GatewayModelBuilder.Escape(p.Name);
                var literal = GatewayModelBuilder.Literal(p.Name);
                switch (p.Kind)
                {
                    case GatewayParameterKind.Route:
                        parameters.Add($"[{Mvc}.FromRoute(Name = {literal})] {GatewayModelBuilder.TypeName(p.Type)} {name}");
                        args.Add(name);
                        break;
                    case GatewayParameterKind.Query:
                        parameters.Add($"[{Mvc}.FromQuery(Name = {literal})] {GatewayModelBuilder.TypeName(p.Type)} {name}");
                        args.Add(name);
                        break;
                    case GatewayParameterKind.QueryCollection:
                        var element = GatewayModelBuilder.TypeName(p.ElementType!);
                        parameters.Add($"[{Mvc}.FromQuery(Name = {literal})] {element}[] {name}");
                        var array = $"({name} ?? global::System.Array.Empty<{element}>())";
                        args.Add(GatewayModelBuilder.AcceptsArray(p.Type)
                            ? array
                            : $"new global::System.Collections.Generic.List<{element}>({array})");
                        break;
                    case GatewayParameterKind.Body:
                        parameters.Add($"[{Mvc}.FromBody] {GatewayModelBuilder.TypeName(p.Type)} {name}");
                        args.Add(name);
                        break;
                }
            }

            sb.AppendLine($"    public async global::System.Threading.Tasks.Task<{Mvc}.IActionResult> {m.ActionName}({string.Join(", ", parameters)})");
            sb.AppendLine("    {");
            sb.AppendLine("        try");
            sb.AppendLine("        {");
            sb.AppendLine($"            var __response = await _client.{m.Method.Name}({string.Join(", ", args)}).ConfigureAwait(false);");
            sb.AppendLine(m.IsBinary
                ? $"            return {Results}.Binary(__response, HttpContext);"
                : $"            return {Results}.Json(__response, HttpContext);");
            sb.AppendLine("        }");
            sb.AppendLine("        catch (global::System.Exception __ex) when (!HttpContext.RequestAborted.IsCancellationRequested)");
            sb.AppendLine("        {");
            sb.AppendLine($"            return {Results}.Failure<{resultType}>(__ex, HttpContext, _logger, {GatewayModelBuilder.Literal(m.ActionName)});");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    internal static string EmitClient(GatewayTarget target)
    {
        var iface = target.InterfaceType!;
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// Generated by Grunt.SourceGenerator.GatewayGenerator from [GatewayExposed] methods of " + target.ClientType.ToDisplayString() + ".");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {target.Namespace};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// {iface.Name} over the Halo gateway's HTTP API (typed HttpClient). Exposed methods call the gateway routes and rebuild the");
        sb.AppendLine("/// HaloApiResultContainer; the gateway does Halo auth and upstream retries, this client only retries its own transport");
        sb.AppendLine("/// (gateway unreachable, 5xx/429 from the gateway itself). Methods the gateway does not expose throw NotSupportedException.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"public partial class {ClientClassName} : {GatewayModelBuilder.TypeName(iface)}");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Route prefix of the gateway this client was generated for.</summary>");
        sb.AppendLine($"    public const string RoutePrefix = {GatewayModelBuilder.Literal(target.RoutePrefix)};");
        sb.AppendLine();
        sb.AppendLine($"    private readonly {Transport} _transport;");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Typed-client constructor: <c>services.AddHaloGatewayClient(...)</c> registers it with IHttpClientFactory.</summary>");
        sb.AppendLine($"    public {ClientClassName}(global::System.Net.Http.HttpClient httpClient, global::Microsoft.Extensions.Options.IOptions<{ClientOptions}> options, global::Microsoft.Extensions.Logging.ILogger<{ClientClassName}>? logger = null)");
        sb.AppendLine($"        : this(new {Transport}(httpClient, options.Value, logger))");
        sb.AppendLine("    {");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Creates the client over an existing transport.</summary>");
        sb.AppendLine($"    public {ClientClassName}({Transport} transport)");
        sb.AppendLine("    {");
        sb.AppendLine("        _transport = transport;");
        sb.AppendLine("    }");

        var exposedByMethod = target.Methods.ToDictionary(m => m.Method, m => m, SymbolEqualityComparer.Default);

        foreach (var method in iface.GetMembers().OfType<IMethodSymbol>().Where(m => m.MethodKind == MethodKind.Ordinary))
        {
            var classMethod = GatewayModelBuilder.PublicMethods(target.ClientType).FirstOrDefault(c => SameSignature(c, method));
            GatewayMethod? exposed = null;
            if (classMethod is not null)
            {
                exposedByMethod.TryGetValue(classMethod, out exposed);
            }

            var typeParameters = method.TypeParameters.Length > 0
                ? "<" + string.Join(", ", method.TypeParameters.Select(t => t.Name)) + ">"
                : string.Empty;
            var parameters = string.Join(", ", method.Parameters.Select(p => $"{GatewayModelBuilder.TypeName(p.Type)} {GatewayModelBuilder.Escape(p.Name)}"));
            var signature = $"public {GatewayModelBuilder.TypeName(method.ReturnType)} {method.Name}{typeParameters}({parameters})";

            sb.AppendLine();
            if (exposed is null)
            {
                var message = $"{iface.Name}.{method.Name} is not exposed by the Halo gateway. Mark it [GatewayExposed] in Grunt " +
                              "(read-only methods only), or call Halo directly with HaloInfiniteClientFactory.";
                sb.AppendLine($"    /// <summary>Not exposed by the gateway: always throws <see cref=\"global::System.NotSupportedException\"/>.</summary>");
                sb.AppendLine($"    {signature}");
                sb.AppendLine($"        => throw new global::System.NotSupportedException({GatewayModelBuilder.Literal(message)});");
                continue;
            }

            sb.AppendLine($"    /// <summary>{exposed.HttpMethod} {GatewayModelBuilder.Xml(target.RoutePrefix + "/" + exposed.Route)} on the gateway.</summary>");
            sb.AppendLine($"    {signature}");
            sb.AppendLine("    {");
            sb.AppendLine($"        var __path = {BuildPathExpression(target.RoutePrefix, exposed)};");
            sb.AppendLine($"        var __query = new {UriHelper}.QueryBuilder();");
            string body = "null";
            foreach (var p in exposed.Parameters)
            {
                var name = GatewayModelBuilder.Escape(p.Name);
                switch (p.Kind)
                {
                    case GatewayParameterKind.Query:
                        sb.AppendLine($"        __query.Add({GatewayModelBuilder.Literal(p.Name)}, {name});");
                        break;
                    case GatewayParameterKind.QueryCollection:
                        sb.AppendLine($"        __query.AddAll({GatewayModelBuilder.Literal(p.Name)}, {name});");
                        break;
                    case GatewayParameterKind.Body:
                        body = name;
                        break;
                }
            }
            var verb = exposed.HttpMethod switch
            {
                "POST" => "global::System.Net.Http.HttpMethod.Post",
                "PUT" => "global::System.Net.Http.HttpMethod.Put",
                "PATCH" => "global::System.Net.Http.HttpMethod.Patch",
                "DELETE" => "global::System.Net.Http.HttpMethod.Delete",
                _ => "global::System.Net.Http.HttpMethod.Get",
            };
            var resultType = GatewayModelBuilder.TypeName(exposed.ResultType);
            var call = exposed.IsBinary
                ? $"_transport.SendBinaryAsync({verb}, __path + __query.ToString(), {body}, {GatewayModelBuilder.Literal(exposed.ActionName)})"
                : $"_transport.SendAsync<{resultType}>({verb}, __path + __query.ToString(), {body}, {GatewayModelBuilder.Literal(exposed.ActionName)})";
            sb.AppendLine($"        return {call};");
            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string BuildPathExpression(string prefix, GatewayMethod method)
    {
        var parts = new List<string>();
        var literal = new StringBuilder(prefix.Length > 0 ? prefix + "/" : string.Empty);
        var route = method.Route;
        var i = 0;
        while (i < route.Length)
        {
            var open = route.IndexOf('{', i);
            if (open < 0)
            {
                literal.Append(route.Substring(i));
                break;
            }
            literal.Append(route.Substring(i, open - i));
            var close = route.IndexOf('}', open);
            var token = route.Substring(open + 1, close - open - 1);
            var catchAll = token.StartsWith("*");
            token = token.TrimStart('*');
            var end = token.IndexOfAny(new[] { ':', '?', '=' });
            var name = end >= 0 ? token.Substring(0, end) : token;
            if (literal.Length > 0)
            {
                parts.Add(GatewayModelBuilder.Literal(literal.ToString()));
                literal.Clear();
            }
            parts.Add($"{UriHelper}.{(catchAll ? "CatchAll" : "Segment")}({GatewayModelBuilder.Escape(name)})");
            i = close + 1;
        }
        if (literal.Length > 0)
        {
            parts.Add(GatewayModelBuilder.Literal(literal.ToString()));
        }
        return parts.Count == 0 ? "\"\"" : string.Join(" + ", parts);
    }

    private static bool SameSignature(IMethodSymbol a, IMethodSymbol b)
    {
        if (a.Name != b.Name || a.Parameters.Length != b.Parameters.Length || a.TypeParameters.Length != b.TypeParameters.Length)
            return false;
        for (var i = 0; i < a.Parameters.Length; i++)
        {
            var ta = a.Parameters[i].Type;
            var tb = b.Parameters[i].Type;
            if (ta.TypeKind == TypeKind.TypeParameter && tb.TypeKind == TypeKind.TypeParameter)
                continue;
            if (ta.ToDisplayString(GatewayModelBuilder.TypeFormat) != tb.ToDisplayString(GatewayModelBuilder.TypeFormat))
                return false;
        }
        return true;
    }
}
