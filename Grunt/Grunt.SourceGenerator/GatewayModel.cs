/// <summary>
/// Reads [GatewayExposed] methods of a client type (from source or metadata) into <see cref="GatewayMethod"/>s, reporting
/// diagnostics for methods that cannot be exposed.
/// </summary>
internal static class GatewayModelBuilder
{
    public const string AttributesNamespace = "Surprenant.Grunt.Attributes";
    public const string ExposedAttributeName = AttributesNamespace + ".GatewayExposedAttribute";
    public const string ControllerAttributeName = AttributesNamespace + ".GenerateGatewayControllerAttribute";
    public const string ClientAttributeName = AttributesNamespace + ".GenerateGatewayClientAttribute";
    public const string DefaultRoutePrefix = "halo/v1";

    private static readonly string[] HttpMethods = { "GET", "POST", "PUT", "PATCH", "DELETE" };

    public static GatewayTarget? ReadTarget(Compilation compilation, string markerAttributeName)
    {
        var attribute = compilation.Assembly.GetAttributes()
            .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == markerAttributeName);
        if (attribute is null || attribute.ConstructorArguments.Length == 0 ||
            attribute.ConstructorArguments[0].Value is not INamedTypeSymbol clientType)
        {
            return null;
        }

        string routePrefix = DefaultRoutePrefix;
        string? ns = null;
        foreach (var named in attribute.NamedArguments)
        {
            if (named.Key == "RoutePrefix" && named.Value.Value is string prefix)
                routePrefix = prefix.Trim('/');
            else if (named.Key == "Namespace" && named.Value.Value is string n && n.Length > 0)
                ns = n;
        }

        var interfaceName = "I" + clientType.Name;
        var interfaceType = clientType.ContainingNamespace.GetTypeMembers(interfaceName).FirstOrDefault(t => t.TypeKind == TypeKind.Interface)
            ?? clientType.AllInterfaces.FirstOrDefault(i => i.Name == interfaceName);

        return new GatewayTarget(clientType, interfaceType, routePrefix, ns ?? compilation.AssemblyName ?? "Generated");
    }

    public static IEnumerable<IMethodSymbol> PublicMethods(INamedTypeSymbol type) => type.GetMembers()
        .OfType<IMethodSymbol>()
        .Where(m => m.DeclaredAccessibility == Accessibility.Public &&
                    !m.IsStatic &&
                    m.MethodKind == MethodKind.Ordinary &&
                    !m.IsImplicitlyDeclared &&
                    m.Name != "Equals" && m.Name != "GetHashCode" && m.Name != "ToString");

    public static AttributeData? GetExposedAttribute(IMethodSymbol method)
        => method.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == ExposedAttributeName);

    public static void Populate(GatewayTarget target, Action<Diagnostic> report)
    {
        var actionNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var method in PublicMethods(target.ClientType))
        {
            var attribute = GetExposedAttribute(method);
            if (attribute is null)
                continue;

            var built = Build(method, attribute, report);
            if (built is null)
                continue;

            if (!actionNames.Add(built.ActionName))
            {
                report(Diagnostic.Create(GatewayDiagnostics.DuplicateAction, LocationOf(method), Display(method), built.ActionName));
                continue;
            }
            target.Methods.Add(built);
        }
    }

    public static string Display(IMethodSymbol method)
        => method.ContainingType.Name + "." + method.Name + "(" + string.Join(", ", method.Parameters.Select(p => p.Type.ToDisplayString())) + ")";

    public static Location LocationOf(ISymbol symbol)
        => symbol.Locations.FirstOrDefault(l => l.IsInSource) ?? Location.None;

    private static GatewayMethod? Build(IMethodSymbol method, AttributeData attribute, Action<Diagnostic> report)
    {
        var location = LocationOf(method);
        var display = Display(method);

        if (method.IsGenericMethod)
        {
            report(Diagnostic.Create(GatewayDiagnostics.GenericMethod, location, display));
            return null;
        }

        var resultType = GetResultType(method.ReturnType);
        if (resultType is null)
        {
            report(Diagnostic.Create(GatewayDiagnostics.UnsupportedReturnType, location, display));
            return null;
        }

        var route = (attribute.ConstructorArguments.Length > 0 ? attribute.ConstructorArguments[0].Value as string : null) ?? string.Empty;
        route = route.Trim('/');
        var httpMethod = "GET";
        int cache = 0, cacheSeconds = 0;
        string? name = null;
        foreach (var named in attribute.NamedArguments)
        {
            switch (named.Key)
            {
                case "HttpMethod" when named.Value.Value is string verb:
                    httpMethod = verb.Trim().ToUpperInvariant();
                    break;
                case "Cache" when named.Value.Value is int c:
                    cache = c;
                    break;
                case "CacheSeconds" when named.Value.Value is int s:
                    cacheSeconds = s;
                    break;
                case "Name" when named.Value.Value is string n && n.Length > 0:
                    name = n;
                    break;
            }
        }

        if (Array.IndexOf(HttpMethods, httpMethod) < 0)
        {
            report(Diagnostic.Create(GatewayDiagnostics.InvalidHttpMethod, location, display, httpMethod));
            return null;
        }

        if (!TryParseRouteParameters(route, out var routeParameterNames, out var routeError))
        {
            report(Diagnostic.Create(GatewayDiagnostics.InvalidRoute, location, display, routeError));
            return null;
        }

        var parameters = new List<GatewayParameter>();
        var bodyCount = 0;
        foreach (var p in method.Parameters)
        {
            var inRoute = routeParameterNames.Contains(p.Name);
            if (inRoute)
            {
                if (!IsSimple(p.Type))
                {
                    report(Diagnostic.Create(GatewayDiagnostics.InvalidRoute, location, display,
                        $"route parameter '{p.Name}' must be a simple type (string, number, bool, enum, Guid, date)"));
                    return null;
                }
                parameters.Add(new GatewayParameter(p, GatewayParameterKind.Route, null));
            }
            else if (IsSimple(p.Type))
            {
                parameters.Add(new GatewayParameter(p, GatewayParameterKind.Query, null));
            }
            else if (TryGetSimpleCollectionElement(p.Type, out var element))
            {
                parameters.Add(new GatewayParameter(p, GatewayParameterKind.QueryCollection, element));
            }
            else
            {
                bodyCount++;
                parameters.Add(new GatewayParameter(p, GatewayParameterKind.Body, null));
            }
        }

        foreach (var routeName in routeParameterNames)
        {
            if (!method.Parameters.Any(p => p.Name == routeName))
            {
                report(Diagnostic.Create(GatewayDiagnostics.InvalidRoute, location, display,
                    $"route placeholder '{{{routeName}}}' does not match any parameter"));
                return null;
            }
        }

        if (bodyCount > 1)
        {
            report(Diagnostic.Create(GatewayDiagnostics.InvalidBody, location, display,
                "only one complex parameter can be sent as the JSON body"));
            return null;
        }
        if (bodyCount == 1 && (httpMethod == "GET" || httpMethod == "DELETE"))
        {
            report(Diagnostic.Create(GatewayDiagnostics.InvalidBody, location, display,
                $"complex parameters are sent as a JSON body, which needs HttpMethod = \"POST\" (or PUT/PATCH), not {httpMethod}"));
            return null;
        }

        return new GatewayMethod(method, route, httpMethod, cache, cacheSeconds, name ?? method.Name, resultType, parameters);
    }

    /// <summary>T of <c>Task&lt;HaloApiResultContainer&lt;T, HaloApiErrorContainer&gt;&gt;</c>, or null.</summary>
    public static ITypeSymbol? GetResultType(ITypeSymbol returnType)
    {
        if (returnType is INamedTypeSymbol { Name: "Task", TypeArguments.Length: 1 } task &&
            task.ContainingNamespace.ToDisplayString() == "System.Threading.Tasks" &&
            task.TypeArguments[0] is INamedTypeSymbol { Name: "HaloApiResultContainer", TypeArguments.Length: 2 } container &&
            container.TypeArguments[1].Name == "HaloApiErrorContainer")
        {
            return container.TypeArguments[0];
        }
        return null;
    }

    /// <summary>Placeholder names of a route template: <c>{name}</c>, <c>{name:constraint}</c>, <c>{name?}</c>, <c>{*name}</c>.</summary>
    public static bool TryParseRouteParameters(string route, out HashSet<string> names, out string error)
    {
        names = new HashSet<string>(StringComparer.Ordinal);
        error = string.Empty;
        var i = 0;
        while (i < route.Length)
        {
            var open = route.IndexOf('{', i);
            if (open < 0)
            {
                if (route.IndexOf('}', i) >= 0)
                {
                    error = "unbalanced '}' in route template";
                    return false;
                }
                break;
            }
            var close = route.IndexOf('}', open);
            if (close < 0)
            {
                error = "unbalanced '{' in route template";
                return false;
            }
            var token = route.Substring(open + 1, close - open - 1).TrimStart('*');
            var end = token.IndexOfAny(new[] { ':', '?', '=' });
            var name = end >= 0 ? token.Substring(0, end) : token;
            if (name.Length == 0)
            {
                error = "empty route placeholder";
                return false;
            }
            names.Add(name);
            i = close + 1;
        }
        return true;
    }

    public static bool IsSimple(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable)
            return IsSimple(nullable.TypeArguments[0]);
        if (type.TypeKind == TypeKind.Enum)
            return true;
        switch (type.SpecialType)
        {
            case SpecialType.System_String:
            case SpecialType.System_Boolean:
            case SpecialType.System_Char:
            case SpecialType.System_Byte:
            case SpecialType.System_SByte:
            case SpecialType.System_Int16:
            case SpecialType.System_UInt16:
            case SpecialType.System_Int32:
            case SpecialType.System_UInt32:
            case SpecialType.System_Int64:
            case SpecialType.System_UInt64:
            case SpecialType.System_Single:
            case SpecialType.System_Double:
            case SpecialType.System_Decimal:
            case SpecialType.System_DateTime:
                return true;
        }
        var full = type.ToDisplayString();
        return full is "System.Guid" or "System.DateTimeOffset" or "System.TimeSpan";
    }

    /// <summary>Arrays, List&lt;T&gt; and the IEnumerable/ICollection/IList/IReadOnly* interfaces of a simple T.</summary>
    public static bool TryGetSimpleCollectionElement(ITypeSymbol type, out ITypeSymbol? element)
    {
        element = null;
        if (type is IArrayTypeSymbol { Rank: 1 } array && IsSimple(array.ElementType))
        {
            element = array.ElementType;
            return true;
        }
        if (type is INamedTypeSymbol { TypeArguments.Length: 1 } named && IsSimple(named.TypeArguments[0]))
        {
            var definition = named.OriginalDefinition.ToDisplayString();
            switch (definition)
            {
                case "System.Collections.Generic.List<T>":
                case "System.Collections.Generic.IEnumerable<T>":
                case "System.Collections.Generic.ICollection<T>":
                case "System.Collections.Generic.IList<T>":
                case "System.Collections.Generic.IReadOnlyCollection<T>":
                case "System.Collections.Generic.IReadOnlyList<T>":
                    element = named.TypeArguments[0];
                    return true;
            }
        }
        return false;
    }

    /// <summary>Whether a T[] can be passed where <paramref name="type"/> is expected (arrays and the interfaces above).</summary>
    public static bool AcceptsArray(ITypeSymbol type)
        => type is IArrayTypeSymbol || type.OriginalDefinition.ToDisplayString() != "System.Collections.Generic.List<T>";

    public static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat;

    public static string TypeName(ITypeSymbol type) => type.ToDisplayString(TypeFormat);

    public static string Escape(string identifier)
        => SyntaxFactsHelper.IsKeyword(identifier) ? "@" + identifier : identifier;

    public static string Xml(string value)
        => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    public static string Literal(string value)
        => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}

internal static class SyntaxFactsHelper
{
    public static bool IsKeyword(string identifier)
        => Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(identifier) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None;
}
