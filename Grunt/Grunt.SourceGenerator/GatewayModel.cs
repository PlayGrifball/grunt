        Category, DiagnosticSeverity.Error, isEnabledByDefault: true);

    public static readonly DiagnosticDescriptor InvalidBody = new(
        "GRUNTGW002", "Invalid body parameter",
        "'{0}': {1}",
        Category, DiagnosticSeverity.Error, isEnabledByDefault: true);

    public static readonly DiagnosticDescriptor DuplicateAction = new(
        "GRUNTGW003", "Duplicate gateway action name",
        "'{0}' maps to action name '{1}', which is already used; set [GatewayExposed(Name = ...)] to tell overloads apart",
        Category, DiagnosticSeverity.Error, isEnabledByDefault: true);

    public static readonly DiagnosticDescriptor InvalidRoute = new(
        "GRUNTGW004", "Invalid gateway route",
        "'{0}': {1}",
        Category, DiagnosticSeverity.Error, isEnabledByDefault: true);

    public static readonly DiagnosticDescriptor UnsupportedReturnType = new(
        "GRUNTGW005", "Unsupported return type",
        "'{0}' must return Task<HaloApiResultContainer<T, HaloApiErrorContainer>> to be exposed through the gateway",
