using Microsoft.CodeAnalysis;
using System;
using System.Collections.Generic;
using System.Linq;

namespace Grunt.SourceGenerator;

internal enum GatewayParameterKind
{
    Route,
    Query,
    QueryCollection,
    Body,
}

internal sealed class GatewayParameter
{
    public GatewayParameter(IParameterSymbol symbol, GatewayParameterKind kind, ITypeSymbol? elementType)
    {
        Symbol = symbol;
        Kind = kind;
        ElementType = elementType;
    }

    public IParameterSymbol Symbol { get; }
    public string Name => Symbol.Name;
    public ITypeSymbol Type => Symbol.Type;
    public GatewayParameterKind Kind { get; }

    /// <summary>Element type for <see cref="GatewayParameterKind.QueryCollection"/>.</summary>
    public ITypeSymbol? ElementType { get; }
}

internal sealed class GatewayMethod
{
    public GatewayMethod(IMethodSymbol method, string route, string httpMethod, int cachePolicy, int cacheSeconds, string actionName,
        ITypeSymbol resultType, IReadOnlyList<GatewayParameter> parameters)
    {
        Method = method;
        Route = route;
        HttpMethod = httpMethod;
        CachePolicy = cachePolicy;
        CacheSeconds = cacheSeconds;
        ActionName = actionName;
        ResultType = resultType;
        Parameters = parameters;
    }

    public IMethodSymbol Method { get; }
    public string Route { get; }
    public string HttpMethod { get; }
    public int CachePolicy { get; }
    public int CacheSeconds { get; }
    public string ActionName { get; }

    /// <summary>T in <c>Task&lt;HaloApiResultContainer&lt;T, HaloApiErrorContainer&gt;&gt;</c>.</summary>
    public ITypeSymbol ResultType { get; }
    public IReadOnlyList<GatewayParameter> Parameters { get; }

    public bool IsBinary => ResultType is IArrayTypeSymbol { ElementType.SpecialType: SpecialType.System_Byte };
}

internal sealed class GatewayTarget
{
    public GatewayTarget(INamedTypeSymbol clientType, INamedTypeSymbol? interfaceType, string routePrefix, string @namespace)
    {
        ClientType = clientType;
        InterfaceType = interfaceType;
        RoutePrefix = routePrefix;
        Namespace = @namespace;
    }

    public INamedTypeSymbol ClientType { get; }
    public INamedTypeSymbol? InterfaceType { get; }
    public string RoutePrefix { get; }
    public string Namespace { get; }

    /// <summary>Exposed methods that passed validation.</summary>
    public List<GatewayMethod> Methods { get; } = new();
}

